def find_input_csv(root, filename):
    """Find an expected V12 CSV at the root or in any nested result folder."""
    if not root.exists():
        raise FileNotFoundError(
            f"Le dossier de résultats n'existe pas : {root}\n"
            "Vérifie le chemin OUT dans la section CONFIG."
        )
    matches = [p for p in root.rglob("*") if p.is_file()
               and p.name.lower() == filename.lower()
               and OUTPUT_DIR not in p.parents]
    if not matches:
        visible = []
        for p in list(root.iterdir())[:40]:
            visible.append(("[Dossier] " if p.is_dir() else "[Fichier] ") + p.name)
        listing = "\n  ".join(visible) if visible else "(dossier vide)"
        raise FileNotFoundError(
            f"Impossible de trouver {filename} dans : {root}\n"
            f"Recherche effectuée aussi dans tous les sous-dossiers.\n"
            f"Éléments présents à la racine :\n  {listing}\n\n"
            "Ce fichier doit être généré par V12.4.1. Si tu ne le vois pas, "
            "le traitement V12 n'a probablement pas exporté ce CSV dans ce dossier."
        )
    # Prefer the file closest to OUT; if there are several, use the most recently modified.
    matches.sort(key=lambda p: (len(p.relative_to(root).parts), -p.stat().st_mtime))
    if len(matches) > 1:
        print(f"Attention : {len(matches)} fichiers {filename} trouvés. "
              f"Utilisation de : {matches[0]}")
    return matches[0]


def numeric_clean(df, cols):
    out = df.copy()
    for c in cols:
        if c in out:
            out[c] = pd.to_numeric(out[c], errors="coerce")
    return out


def qsummary(x):
    x = pd.Series(x).replace([np.inf, -np.inf], np.nan).dropna()
    if x.empty:
        return {"N": 0, "median": np.nan, "Q1": np.nan, "Q3": np.nan,
                "mean": np.nan, "SD": np.nan}
    return {
        "N": int(x.size), "median": float(x.median()),
        "Q1": float(x.quantile(.25)), "Q3": float(x.quantile(.75)),
        "mean": float(x.mean()),
        "SD": float(x.std(ddof=1)) if len(x) > 1 else np.nan,
    }


def add_cluster_ids(df):
    """Create unique IDs for participant/trial/marker variance components."""
    d = df.copy()
    d["Subject"] = d["Subject"].astype(str)
    d["File"] = d["File"].astype(str)
    d["Marker"] = d["Marker"].astype(str)
    return d


def fit_vc_model(data, outcome, predictor=None):
    """
    Cross-classified variance-components mixed model.
    Trial IDs are unique filenames and nested in participants in this dataset.
    Participant, trial and marker random intercepts are included.
    """
    d = data.copy()
    formula = outcome if predictor is None else f"{outcome} ~ {predictor}"
    if predictor is None:
        formula = f"{outcome} ~ 1"
    model = smf.mixedlm(
        formula, data=d, groups=np.ones(len(d)), re_formula="0",
        vc_formula={
            "Subject": "0 + C(Subject)",
            "Trial": "0 + C(File)",
            "Marker": "0 + C(Marker)",
        },
    )
    fit = model.fit(reml=True, method=["lbfgs", "powell"],
                    maxiter=2500, disp=False)
    if not fit.converged:
        raise RuntimeError("MixedLM did not converge")
    return fit


def extract_variances(fit):
    vc = dict(zip(fit.model.exog_vc.names,
                  np.asarray(fit.vcomp, dtype=float)))
    return {
        "var_subject": max(0.0, float(vc.get("Subject", 0.0))),
        "var_trial": max(0.0, float(vc.get("Trial", 0.0))),
        "var_marker": max(0.0, float(vc.get("Marker", 0.0))),
        "var_residual": max(0.0, float(fit.scale)),
    }


def repeated_ba(data, n_boot=N_BOOT, seed=RANDOM_SEED):
    """
    Repeated-measures Bland–Altman:
      bias = fixed intercept from mixed model
      LoA = bias +/- 1.96 * total SD from participant + trial + marker
            + residual variance components.
    CI for bias and LoA are obtained by participant-cluster bootstrap,
    refitting the same model in each resample.
    """
    d = data.copy()
    d = d.replace([np.inf, -np.inf], np.nan).dropna(
        subset=["Subject", "File", "Marker", "Mean", "Diff"])
    if d["Subject"].nunique() < 3 or len(d) < 10:
        raise ValueError("Insufficient data for repeated-measures Bland–Altman")

    fit = fit_vc_model(d, "Diff")
    bias = float(fit.fe_params["Intercept"])
    vv = extract_variances(fit)
    sd_total = float(np.sqrt(sum(vv.values())))
    loa_low = bias - 1.96 * sd_total
    loa_high = bias + 1.96 * sd_total

    rng = np.random.default_rng(seed)
    subjects = d["Subject"].unique()
    boot_bias, boot_low, boot_high = [], [], []
    n_failed = 0
    start_time = time.time()
    print(f"\nBootstrap Bland–Altman : 0/{n_boot} (0 %) ", flush=True)

    for b in range(n_boot):
        sampled = rng.choice(subjects, size=len(subjects), replace=True)
        chunks = []
        for j, sid in enumerate(sampled):
            chunk = d[d["Subject"] == sid].copy()
            # Relabel duplicated clusters so they remain distinct bootstrap draws.
            chunk["Subject"] = f"boot{j}_{sid}"
            chunk["File"] = chunk["File"].astype(str).map(
                lambda x: f"boot{j}_{x}")
            chunks.append(chunk)
        bd = pd.concat(chunks, ignore_index=True)
        try:
            bf = fit_vc_model(bd, "Diff")
            bb = float(bf.fe_params["Intercept"])
            bv = extract_variances(bf)
            bsd = float(np.sqrt(sum(bv.values())))
            boot_bias.append(bb)
            boot_low.append(bb - 1.96 * bsd)
            boot_high.append(bb + 1.96 * bsd)
        except Exception:
            n_failed += 1

        # Affichage régulier de l'avancement dans la console Spyder.
        completed = b + 1
        if completed == n_boot or completed % max(1, n_boot // 20) == 0:
            elapsed = time.time() - start_time
            pct = 100.0 * completed / n_boot
            print(
                f"Bootstrap Bland–Altman : {completed}/{n_boot} "
                f"({pct:.0f} %) | réussis : {len(boot_bias)} "
                f"| échecs : {n_failed} | temps : {elapsed:.1f} s",
                flush=True
            )

    def ci(values):
        if len(values) < MIN_BOOT_SUCCESS:
            return (np.nan, np.nan)
        return tuple(np.percentile(values, [2.5, 97.5]).astype(float))

    bias_ci = ci(boot_bias)
    low_ci = ci(boot_low)
    high_ci = ci(boot_high)
    bootstrap_status = (
        "OK" if len(boot_bias) >= MIN_BOOT_SUCCESS
        else "INSUFFICIENT_SUCCESSFUL_REPLICATES"
    )

    result = {
        "N_observations": int(len(d)),
        "N_participants": int(d.Subject.nunique()),
        "N_trials": int(d.File.nunique()),
        "N_markers": int(d.Marker.nunique()),
        "Difference": "Headband - Dental splint",
        "Model": "Mixed variance components: participant + trial + marker + residual",
        "Bootstrap_requested": int(n_boot),
        "Bootstrap_successful": int(len(boot_bias)),
        "Bootstrap_failed": int(n_failed),
        "Bootstrap_min_success_for_CI": int(MIN_BOOT_SUCCESS),
        "Bootstrap_status": bootstrap_status,
        "Bootstrap_mode": BOOTSTRAP_MODE.upper(),
        "Bootstrap_elapsed_seconds": float(time.time() - start_time),
        "Bias_mm": bias,
        "Bias_CI95_low": bias_ci[0], "Bias_CI95_high": bias_ci[1],
        "SD_subject_mm": np.sqrt(vv["var_subject"]),
        "SD_trial_mm": np.sqrt(vv["var_trial"]),
        "SD_marker_mm": np.sqrt(vv["var_marker"]),
        "SD_residual_mm": np.sqrt(vv["var_residual"]),
        "SD_total_mm": sd_total,
        "LoA_lower_mm": loa_low, "LoA_upper_mm": loa_high,
        "LoA_lower_CI95_low": low_ci[0], "LoA_lower_CI95_high": low_ci[1],
        "LoA_upper_CI95_low": high_ci[0], "LoA_upper_CI95_high": high_ci[1],
        "Bootstrap_requested": int(n_boot),
        "Bootstrap_success": int(len(boot_bias)),
        "Model_converged": bool(fit.converged),
    }
    return d, result


def mixed_slope(data, outcome, predictor, label):
    """
    Mixed model with participant, trial and marker variance components.
    Movement is included as a fixed categorical adjustment because movement
    type is associated with the amplitude distribution.
    """
    d = data.replace([np.inf, -np.inf], np.nan).dropna(
        subset=["Subject", "File", "Marker", "Movement", outcome, predictor]).copy()
    formula = f"{outcome} ~ {predictor} + C(Movement)"
    model = smf.mixedlm(
        formula, data=d, groups=np.ones(len(d)), re_formula="0",
        vc_formula={
            "Subject": "0 + C(Subject)",
            "Trial": "0 + C(File)",
            "Marker": "0 + C(Marker)",
        },
    )
    fit = model.fit(reml=True, method=["lbfgs", "powell"],
                    maxiter=2500, disp=False)
    if not fit.converged:
        raise RuntimeError(f"MixedLM did not converge: {label}")
    ci = fit.conf_int()
    return {
        "Analysis": label,
        "N_observations": int(len(d)),
        "N_participants": int(d.Subject.nunique()),
        "N_trials": int(d.File.nunique()),
        "N_movements": int(d.Movement.nunique()),
        "Model": "MixedLM + participant/trial/marker variance components; movement fixed effect",
        "Intercept": float(fit.fe_params["Intercept"]),
        "Slope": float(fit.fe_params[predictor]),
        "Slope_CI95_low": float(ci.loc[predictor, 0]),
        "Slope_CI95_high": float(ci.loc[predictor, 1]),
        "Slope_p": float(fit.pvalues[predictor]),
        "Model_converged": bool(fit.converged),
    }, fit



def safe_mixed_slope(data, outcome, predictor, label):
    """Run a secondary slope model without aborting the complete pipeline."""
    try:
        row, fit = mixed_slope(data, outcome, predictor, label)
        row["Status"] = "Estimated"
        row["Error"] = ""
        return row, fit
    except Exception as exc:
        return ({
            "Analysis": label,
            "Status": "Not estimable",
            "Model_converged": False,
            "Error": f"{type(exc).__name__}: {exc}",
        }, None)


def movement_participant_bootstrap(data, movement, n_boot=1000, seed=RANDOM_SEED):
    """
    Mouvement-specific descriptive inference with equal participant weighting.
    First calculate one participant-level mean signed difference, then bootstrap
    participants. This avoids unstable movement-specific variance-component
    MixedLMs. These are participant-balanced bias estimates, NOT individual-level
    repeated-measures limits of agreement.
    """
    z = data.replace([np.inf, -np.inf], np.nan).dropna(
        subset=["Subject", "File", "Marker", "Diff"]).copy()
    if z["Subject"].nunique() < 3:
        raise ValueError(f"{movement}: fewer than 3 participants")
    subj = z.groupby("Subject", as_index=False).agg(
        Participant_mean_bias_mm=("Diff", "mean"),
        Participant_median_bias_mm=("Diff", "median"),
        N_trials=("File", "nunique"),
        N_marker_trial_pairs=("Diff", "size"),
    )
    vals = subj["Participant_mean_bias_mm"].to_numpy(dtype=float)
    rng = np.random.default_rng(seed + sum(ord(c) for c in str(movement)))
    boot = []
    for _ in range(n_boot):
        sample = rng.choice(vals, size=len(vals), replace=True)
        boot.append(float(np.mean(sample)))
    ci = np.percentile(boot, [2.5, 97.5])
    return {
        "Movement": str(movement),
        "N_observations": int(len(z)),
        "N_participants": int(z.Subject.nunique()),
        "N_trials": int(z.File.nunique()),
        "N_markers": int(z.Marker.nunique()),
        "Participant_balanced_mean_bias_mm": float(np.mean(vals)),
        "Bias_bootstrap_CI95_low": float(ci[0]),
        "Bias_bootstrap_CI95_high": float(ci[1]),
        "SD_between_participant_means_mm": float(np.std(vals, ddof=1)),
        "Median_participant_mean_bias_mm": float(np.median(vals)),
        "Bootstrap_requested": int(n_boot),
        "Bootstrap_successful": int(len(boot)),
        "Interpretation": (
            "Participant-balanced movement-specific bias; participant bootstrap. "
            "Not individual-level limits of agreement."
        ),
        "Model": "Participant-level aggregation + participant bootstrap",
    }, subj

def leave_one_subject_out(data):
    """Influence analysis: refit the primary BA model after omitting each subject."""
    rows = []
    subjects = sorted(data["Subject"].astype(str).unique())
    full = fit_vc_model(data, "Diff")
    full_bias = float(full.fe_params["Intercept"])
    full_vv = extract_variances(full)
    full_sd = float(np.sqrt(sum(full_vv.values())))
    full_low, full_high = full_bias - 1.96 * full_sd, full_bias + 1.96 * full_sd

    for subject in subjects:
        z = data[data["Subject"].astype(str) != subject].copy()
        row = {
            "Omitted_subject": subject,
            "N_participants": int(z.Subject.nunique()),
            "N_observations": int(len(z)),
            "Full_sample_bias_mm": full_bias,
            "Full_sample_LoA_lower_mm": full_low,
            "Full_sample_LoA_upper_mm": full_high,
        }
        try:
            fit = fit_vc_model(z, "Diff")
            bias = float(fit.fe_params["Intercept"])
            vv = extract_variances(fit)
            sd = float(np.sqrt(sum(vv.values())))
            row.update({
                "Bias_mm": bias,
                "Bias_change_vs_full_mm": bias - full_bias,
                "LoA_lower_mm": bias - 1.96 * sd,
                "LoA_upper_mm": bias + 1.96 * sd,
                "Model_converged": bool(fit.converged),
                "Status": "Estimated",
                "Error": "",
            })
        except Exception as exc:
            row.update({
                "Bias_mm": np.nan,
                "Bias_change_vs_full_mm": np.nan,
                "LoA_lower_mm": np.nan,
                "LoA_upper_mm": np.nan,
                "Model_converged": False,
                "Status": "Not estimable",
                "Error": f"{type(exc).__name__}: {exc}",
            })
        rows.append(row)
        print(f"Influence analysis: participant {subject} processed", flush=True)
    return pd.DataFrame(rows)


def weighted_empirical_quantile(values_by_cluster, quantile):
    """Weighted empirical quantile with equal total weight per participant."""
    arrays = [np.asarray(v, dtype=float) for v in values_by_cluster if len(v)]
    if not arrays:
        return np.nan
    n_clusters = len(arrays)
    values = np.concatenate(arrays)
    weights = np.concatenate([
        np.full(len(a), 1.0 / n_clusters / len(a), dtype=float)
        for a in arrays
    ])
    order = np.argsort(values)
    values = values[order]
    cumulative = np.cumsum(weights[order])
    return float(np.interp(float(quantile), cumulative, values))


def empirical_cluster_loa(data, n_boot=2000, seed=RANDOM_SEED):
    """
    Non-parametric sensitivity analysis for the marginal distribution of
    marker-trial differences. Each participant receives equal total weight.
    Bootstrap resampling is performed at participant level, retaining all
    trials and markers within each sampled participant.

    These are empirical central 95% agreement limits, not a replacement for
    the pre-specified mixed-model primary analysis.
    """
    z = data.replace([np.inf, -np.inf], np.nan).dropna(
        subset=["Subject", "Diff"]
    ).copy()
    clusters = sorted(z.Subject.astype(str).unique())
    arrays = {
        sid: z.loc[z.Subject.astype(str) == sid, "Diff"].to_numpy(dtype=float)
        for sid in clusters
    }
    point_arrays = [arrays[sid] for sid in clusters]
    point = {
        "Empirical_lower_2_5_mm": weighted_empirical_quantile(point_arrays, .025),
        "Empirical_median_mm": weighted_empirical_quantile(point_arrays, .50),
        "Empirical_upper_97_5_mm": weighted_empirical_quantile(point_arrays, .975),
        "Participant_balanced_mean_mm": float(np.mean([a.mean() for a in point_arrays])),
        "N_observations": int(len(z)),
        "N_participants": int(len(clusters)),
        "Bootstrap_requested": int(n_boot),
        "Bootstrap_method": "Participant-cluster bootstrap; equal participant weighting",
        "Interpretation": "Non-parametric sensitivity limits; not the primary model-based LoA",
    }
    rng = np.random.default_rng(seed)
    boots = []
    for _ in range(n_boot):
        sampled = rng.choice(clusters, size=len(clusters), replace=True)
        sampled_arrays = [arrays[str(sid)] for sid in sampled]
        boots.append([
            weighted_empirical_quantile(sampled_arrays, .025),
            weighted_empirical_quantile(sampled_arrays, .50),
            weighted_empirical_quantile(sampled_arrays, .975),
            float(np.mean([a.mean() for a in sampled_arrays])),
        ])
    b = np.asarray(boots, dtype=float)
    names = ["lower_2_5", "median", "upper_97_5", "participant_balanced_mean"]
    for j, name in enumerate(names):
        ci = np.nanpercentile(b[:, j], [2.5, 97.5])
        point[f"{name}_bootstrap_CI95_low"] = float(ci[0])
        point[f"{name}_bootstrap_CI95_high"] = float(ci[1])
    point["Bootstrap_successful"] = int(np.isfinite(b).all(axis=1).sum())
    return point



def amplitude_stratified_agreement(data, n_boot=2000, seed=RANDOM_SEED):
    """
    Descriptive sensitivity analysis across quartiles of mean amplitude.
    Participant-level means and medians are calculated within each stratum;
    bootstrap resampling is at participant level. Quartile cut-points are
    fixed from the full dataset. No marker-trial row is treated as independent.
    """
    z = data.replace([np.inf, -np.inf], np.nan).dropna(
        subset=["Subject", "Mean_amplitude_mm",
                "Signed_difference_mm", "Absolute_difference_mm"]
    ).copy()
    z["Amplitude_stratum"] = pd.qcut(
        z["Mean_amplitude_mm"], q=4,
        labels=["Q1_lowest", "Q2", "Q3", "Q4_highest"],
        duplicates="drop"
    )
    rng = np.random.default_rng(seed)
    rows = []
    for label, g in z.groupby("Amplitude_stratum", observed=True):
        subj = (g.groupby("Subject", as_index=False)
                .agg(
                    Participant_mean_bias_mm=("Signed_difference_mm", "mean"),
                    Participant_median_bias_mm=("Signed_difference_mm", "median"),
                    Participant_mean_absolute_error_mm=("Absolute_difference_mm", "mean"),
                    Participant_median_absolute_error_mm=("Absolute_difference_mm", "median"),
                    N_marker_trial_pairs=("Signed_difference_mm", "size"),
                ))
        subjects = subj["Subject"].astype(str).tolist()
        metric_cols = [
            "Participant_mean_bias_mm",
            "Participant_mean_absolute_error_mm",
            "Participant_median_bias_mm",
            "Participant_median_absolute_error_mm",
        ]
        vals = {c: subj[c].to_numpy(dtype=float) for c in metric_cols}
        boots = {c: [] for c in metric_cols}
        if len(subjects) >= 3:
            for _ in range(n_boot):
                ix = rng.integers(0, len(subjects), size=len(subjects))
                for c in metric_cols:
                    boots[c].append(float(np.mean(vals[c][ix])))
        row = {
            "Amplitude_stratum": str(label),
            "Mean_amplitude_lower_mm": float(g["Mean_amplitude_mm"].min()),
            "Mean_amplitude_upper_mm": float(g["Mean_amplitude_mm"].max()),
            "N_marker_trial_pairs": int(len(g)),
            "N_participants": int(g["Subject"].nunique()),
            "Bootstrap_requested": int(n_boot),
            "Bootstrap_successful": int(n_boot if len(subjects) >= 3 else 0),
            "Interpretation": (
                "Descriptive amplitude-stratified sensitivity; participant-level "
                "aggregation and participant bootstrap. Not separate confirmatory LoA."
            ),
        }
        for c in metric_cols:
            row["Participant_balanced_" + c.replace("Participant_", "")] = float(np.mean(vals[c]))
            if boots[c]:
                ci = np.percentile(boots[c], [2.5, 97.5])
            else:
                ci = [np.nan, np.nan]
            row[c + "_bootstrap_CI95_low"] = float(ci[0])
            row[c + "_bootstrap_CI95_high"] = float(ci[1])
        rows.append(row)
    return pd.DataFrame(rows), z


def extreme_observation_details(data, threshold_mm=7.0, max_rows=100):
    """Export individual large discrepancies for QC review; never exclude them."""
    cols = [
        "Subject", "Movement", "Marker", "File", "Marker_class", "QC",
        "Mean_amplitude_mm", "Signed_difference_mm", "Absolute_difference_mm",
        "Amplitude_splint_mm", "Amplitude_headband_mm",
        "Run_pct", "Interp_pct", "N_frames_run", "N_frames_analysed",
    ]
    present = [c for c in cols if c in data.columns]
    z = data.copy()
    z = z[z["Absolute_difference_mm"] >= float(threshold_mm)]
    return z.sort_values("Absolute_difference_mm", ascending=False)[present].head(max_rows)

def qc_sensitivity(data):
    """Compare the primary model with the QC=ok subset; never changes inclusion."""
    rows = []
    subsets = [("All_analyzable_primary", data)]
    if "QC" in data.columns:
        subsets.append(("QC_ok_only_sensitivity", data[data.QC.astype(str).str.lower() == "ok"].copy()))
        qc_counts = data.QC.astype(str).value_counts(dropna=False).to_dict()
    else:
        qc_counts = {}
    for label, z in subsets:
        row = {
            "Subset": label,
            "N_observations": int(len(z)),
            "N_participants": int(z.Subject.nunique()),
            "N_trials": int(z.File.nunique()),
            "QC_counts_in_full_dataset": str(qc_counts),
        }
        try:
            fit = fit_vc_model(z, "Diff")
            bias = float(fit.fe_params["Intercept"])
            vv = extract_variances(fit)
            sd = float(np.sqrt(sum(vv.values())))
            row.update({
                "Bias_mm": bias,
                "SD_total_mm": sd,
                "LoA_lower_mm": bias - 1.96 * sd,
                "LoA_upper_mm": bias + 1.96 * sd,
                "Model_converged": bool(fit.converged),
                "Status": "Estimated",
            })
        except Exception as exc:
            row.update({"Status": "Not estimable", "Error": f"{type(exc).__name__}: {exc}"})
        rows.append(row)
    return pd.DataFrame(rows)


def participant_balanced_kinematics(data, n_boot=1000, seed=RANDOM_SEED):
    """Summarize V12 trajectory metrics with participant-level resampling.

    Absolute vector RMSE is summarized in all analyzable markers and in the
    jointly-moving subgroup. Relative errors, magnitude correlations and
    direction angles are emphasized in the jointly-moving subgroup only.
    No marker-trial rows are treated as independent inferential replicates.
    """
    specs = {
        "Displacement": {
            "rmse": "Pos_RMSE_mm", "nrmse": "Pos_NRMSE_pct",
            "corr": "Pos_Pearson_norm", "angle": "Pos_Angle_median_deg", "unit": "mm"
        },
        "Velocity": {
            "rmse": "Vel_RMSE_mm_s", "nrmse": "Vel_NRMSE_pct",
            "corr": "Vel_Pearson_norm", "angle": "Vel_Angle_median_deg", "unit": "mm/s"
        },
        "Acceleration": {
            "rmse": "Acc_RMSE_mm_s2", "nrmse": "Acc_NRMSE_pct",
            "corr": "Acc_Pearson_norm", "angle": "Acc_Angle_median_deg", "unit": "mm/s²"
        },
    }
    summary_rows, movement_rows = [], []
    rng = np.random.default_rng(seed + 919)
    for quantity, spec in specs.items():
        for subset_name, subset in [
            ("All_analyzable", data),
            ("Jointly_moving", data[data.Marker_class.astype(str).str.lower() == "moving"]
             if "Marker_class" in data else data.iloc[0:0]),
        ]:
            metrics_to_report = [("Vector_RMSE", spec["rmse"])]
            if subset_name == "Jointly_moving":
                metrics_to_report += [
                    ("NRMSE_pct", spec["nrmse"]),
                    ("Magnitude_Pearson_r", spec["corr"]),
                    ("Median_direction_angle_deg", spec["angle"]),
                ]
            for metric_name, col in metrics_to_report:
                if col not in subset.columns:
                    continue
                z = subset[["Subject", "Movement", col]].replace([np.inf, -np.inf], np.nan).dropna()
                if z.empty:
                    continue
                # Participant medians prevent participants with more rows from dominating.
                pvals = z.groupby("Subject")[col].median().dropna().to_numpy(dtype=float)
                boot = []
                if len(pvals) >= 3:
                    for _ in range(n_boot):
                        boot.append(float(np.mean(rng.choice(pvals, size=len(pvals), replace=True))))
                    ci = np.percentile(boot, [2.5, 97.5])
                else:
                    ci = [np.nan, np.nan]
                summary_rows.append({
                    "Quantity": quantity, "Subset": subset_name, "Metric": metric_name,
                    "Unit": spec["unit"] if metric_name == "Vector_RMSE" else
                            ("%" if metric_name == "NRMSE_pct" else
                             ("r" if metric_name == "Magnitude_Pearson_r" else "degree")),
                    "N_marker_trial_pairs": int(len(z)), "N_participants": int(z.Subject.nunique()),
                    "Pooled_median": float(z[col].median()),
                    "Pooled_Q1": float(z[col].quantile(.25)),
                    "Pooled_Q3": float(z[col].quantile(.75)),
                    "Mean_of_participant_medians": float(np.mean(pvals)),
                    "Median_of_participant_medians": float(np.median(pvals)),
                    "Participant_median_bootstrap_CI95_low": float(ci[0]),
                    "Participant_median_bootstrap_CI95_high": float(ci[1]),
                    "Interpretation": "Descriptive participant-balanced summary; participant bootstrap",
                })
            # Per-movement participant-balanced vector RMSE and relative metrics.
            for movement, gm in subset.groupby("Movement"):
                metrics_to_report = [("Vector_RMSE", spec["rmse"])]
                if subset_name == "Jointly_moving":
                    metrics_to_report += [
                        ("NRMSE_pct", spec["nrmse"]),
                        ("Magnitude_Pearson_r", spec["corr"]),
                        ("Median_direction_angle_deg", spec["angle"]),
                    ]
                for metric_name, col in metrics_to_report:
                    if col not in gm.columns:
                        continue
                    zz = gm[["Subject", col]].replace([np.inf, -np.inf], np.nan).dropna()
                    if zz.empty:
                        continue
                    pp = zz.groupby("Subject")[col].median().to_numpy(dtype=float)
                    bb = [float(np.mean(rng.choice(pp, size=len(pp), replace=True)))
                          for _ in range(n_boot)] if len(pp) >= 3 else []
                    ci2 = np.percentile(bb, [2.5, 97.5]) if bb else [np.nan, np.nan]
                    movement_rows.append({
                        "Quantity": quantity, "Subset": subset_name, "Movement": str(movement),
                        "Metric": metric_name, "Unit": spec["unit"] if metric_name == "Vector_RMSE" else
                                 ("%" if metric_name == "NRMSE_pct" else
                                  ("r" if metric_name == "Magnitude_Pearson_r" else "degree")),
                        "N_marker_trial_pairs": int(len(zz)), "N_participants": int(zz.Subject.nunique()),
                        "Pooled_median": float(zz[col].median()),
                        "Mean_of_participant_medians": float(np.mean(pp)),
                        "Bootstrap_CI95_low": float(ci2[0]), "Bootstrap_CI95_high": float(ci2[1]),
                    })
    return pd.DataFrame(summary_rows), pd.DataFrame(movement_rows)


def extreme_difference_summary(data):
    """Describe tail observations without deleting or down-weighting them."""
    rows = []
    x = data.copy()
    x["AbsDiff"] = x["Diff"].abs()
    for threshold in [3, 5, 7, 10, 15, 20]:
        z = x[x.AbsDiff > threshold]
        rows.append({
            "Absolute_difference_threshold_mm": threshold,
            "N_observations": int(len(z)),
            "Percentage_of_all_observations": float(100 * len(z) / len(x)) if len(x) else np.nan,
            "N_participants": int(z.Subject.nunique()),
            "N_trials": int(z.File.nunique()),
            "N_markers": int(z.Marker.nunique()),
            "Participants": ";".join(sorted(z.Subject.astype(str).unique())),
            "Trials": ";".join(sorted(z.File.astype(str).unique())),
        })
    return pd.DataFrame(rows)


