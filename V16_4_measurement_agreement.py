            beta_series = abs_fit.fe_params
            beta = np.asarray(beta_series, dtype=float)
            cov_all = abs_fit.cov_params()
            cov_fe = np.asarray(
                cov_all.loc[beta_series.index, beta_series.index], dtype=float
            )
    
            movement_levels = sorted(d["Movement"].dropna().astype(str).unique())
            movement_weights = (
                d["Movement"].astype(str).value_counts(normalize=True)
                .reindex(movement_levels).fillna(0.0)
            )
            pred_rows = pd.DataFrame([
                {"Mean_amplitude_mm": x, "Movement": movement}
                for x in grid for movement in movement_levels
            ])
            design_full = np.asarray(
                patsy.build_design_matrices(
                    [abs_fit.model.data.design_info], pred_rows,
                    return_type="dataframe"
                )[0],
                dtype=float,
            )
            design_full = design_full.reshape(len(grid), len(movement_levels), -1)
            weights = movement_weights.to_numpy(dtype=float)
            design = np.einsum("m,gmj->gj", weights, design_full)
    
            pred_mean = design @ beta
            pred_se = np.sqrt(np.maximum(
                0.0, np.einsum("ij,jk,ik->i", design, cov_fe, design)))
            pred_low = pred_mean - 1.96 * pred_se
            pred_high = pred_mean + 1.96 * pred_se
            fig, ax = plt.subplots(figsize=(9, 6))
            ax.scatter(d.Mean_amplitude_mm, d.Absolute_difference_mm,
                       s=14, alpha=.28, label="Marker-trial observations")
            ax.plot(grid, pred_mean, linewidth=2, label="Movement-adjusted mean prediction")
            ax.fill_between(grid, pred_low, pred_high,
                            alpha=.2, label="95% CI of mean prediction")
            ax.set_xlabel("Mean amplitude of the two systems (mm)")
            ax.set_ylabel("Absolute amplitude difference (mm)")
            slope_row = abs_model
            slope_note = (
                f"Adjusted slope: {slope_row.get('Slope', np.nan):.3f} "
                f"(95% CI {slope_row.get('Slope_CI95_low', np.nan):.3f} to "
                f"{slope_row.get('Slope_CI95_high', np.nan):.3f}; "
                f"p={slope_row.get('Slope_p', np.nan):.3g})"
            )
            ax.text(0.02, 0.98, slope_note, transform=ax.transAxes,
                    ha="left", va="top", fontsize=8.5,
                    bbox=dict(boxstyle="round,pad=0.3", facecolor="white",
                              alpha=.85, edgecolor="0.8"))
            ax.set_title("Absolute discrepancy versus mean amplitude")
            ax.legend(fontsize=9)
            fig.tight_layout()
            fig.savefig(OUTPUT_DIR / "Fig_V16_1_02_amplitude_vs_absolute_difference.png",
                        dpi=300, bbox_inches="tight")
            plt.close(fig)
    
